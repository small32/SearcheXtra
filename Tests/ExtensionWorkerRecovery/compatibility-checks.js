const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const assert = require('node:assert/strict');
const source = fs.readFileSync(path.join(__dirname, '../../Sources/SearcheXtra/ExtensionShims.swift'), 'utf8');
const script = source.split('nonisolated static let script = #"""\n')[1].split('\n    """#')[0];
const harness = fs.readFileSync(path.join(__dirname, 'shim-harness.js'), 'utf8');
const fixture = vm.runInNewContext(harness + '\nrecoveryFixture', { console });
const state = fixture(false), calls = [];
state.root.chrome.webRequest = { onBeforeRequest: { addListener: (...args) => calls.push(args) } };
vm.runInNewContext(script.replaceAll('__SEARCH_WORKER_GENERATION__', '0'), state.root);
const callback = () => {};
const filter = { urls: ['https://*/*', 'wss://*/*'], types: ['script', 'webtransport', 'webbundle', 'xmlhttprequest'] };
state.root.chrome.webRequest.onBeforeRequest.addListener(callback, filter, ['blocking', 'extraHeaders', 'requestHeaders']);
assert.equal(calls.length, 1);
assert.equal(calls[0][0], callback);
assert.deepEqual(Array.from(calls[0][1].urls), ['https://*/*']);
assert.deepEqual(Array.from(calls[0][1].types), ['script', 'xmlhttprequest']);
assert.deepEqual(Array.from(calls[0][2]), ['requestHeaders']);
assert.deepEqual(filter.types, ['script', 'webtransport', 'webbundle', 'xmlhttprequest'], 'Caller filter must stay intact');
state.root.chrome.webRequest.onBeforeRequest.addListener(callback, { urls: ['https://*/*'], types: ['webbundle', 'webtransport'] });
assert.equal(calls.length, 1, 'Unsupported-only listener must not be broadened to all request types');
state.root.chrome.webRequest.onBeforeRequest.addListener(callback, { urls: ['https://*/*'], types: ['image'] });
assert.equal(calls.length, 2);
assert.deepEqual(Array.from(calls[1][1].types), ['image']);
console.log('PASS AdBlock mixed request types preserve supported types and listener options');
console.log('PASS unsupported-only request types are not broadened');
console.log('PASS supported filters are unchanged');
